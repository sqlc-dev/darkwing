func TestStatementErrorsV2(t *testing.T) {
	tests := []struct{ sql, msg string }{
		// CREATE TABLE (TransformCreateTableStmt / TransformCreateColumnList)
		{"CREATE TABLE t ()", "Table must have at least one column!"},
		{"CREATE TABLE '' AS SELECT 42", "Empty table name not supported"},
		// TransformColumnDefinition
		{"CREATE TABLE t (Foo)", "Column Foo must have a type or be defined as a GENERATED column."},
		{"CREATE TABLE t (_1a)", `Column "_1a" must have a type or be defined as a GENERATED column.`},
		{"CREATE TABLE t (a INT COLLATE nocase)", "Only VARCHAR columns can have collations!"},
		{"CREATE TABLE t (a VARCHAR[] COLLATE nocase)", "Only VARCHAR columns can have collations!"},
		{"CREATE TABLE t (a VARCHAR COLLATE nocase COLLATE noaccent)", "multiple COLLATE clauses not allowed"},
		{"CREATE TABLE t (a AS (1) COLLATE x)", "Collations are not supported on generated columns"},
		{"CREATE TABLE t (a INT DEFAULT 1 DEFAULT 2)", "Cannot define a default value twice"},
		{"CREATE TABLE t (a INT GENERATED BY DEFAULT AS (1))", "for a generated column, GENERATED ALWAYS must be specified"},
		{"CREATE TABLE t (a INT AS ((SELECT 1)))", `Expression of generated column "a" contains a subquery, which isn't allowed`},
		{"CREATE TABLE t (a INT USING COMPRESSION auto)", "Unrecognized option for column compression, expected none, uncompressed, rle, dictionary, pfor, bitpacking, fsst, chimp, patas, zstd, alp, alprd or roaring"},
		// TransformRelOptionList
		{"CREATE TABLE t (a INT) WITH (x = 1, X = 2)", `Duplicate option "X" in WITH clause`},
		{"CREATE SCHEMA s WITH (a = 1, A = 2)", `Duplicate option "A" in WITH clause`},
		{"ALTER TABLE t SET (a = 1, a = 2)", `Duplicate option "a" in WITH clause`},
		{"ALTER SCHEMA s RESET (a = 2)", `Reset option "a" cannot set any value. Did you mean to use SET?`},
		// TransformCreateStatement
		{"CREATE PERSISTENT TABLE t (a INT)", "PERSISTENT is only supported for CREATE SECRET"},
		{"CREATE TEMP INDEX i ON t (a)", "Temporary indexes are not supported"},
		// TransformCreateViewStmt
		{"CREATE RECURSIVE VIEW v AS SELECT 1", "CREATE RECURSIVE VIEW requires a column list"},
		{"CREATE VIEW v WITH (x) AS SELECT 1", "Only DEFER_BINDING is currently supported as option for CREATE VIEW"},
		// CheckIntegerSequenceOption
		{"CREATE SEQUENCE s INCREMENT BY 1.5", "Expected an integer argument for INCREMENT, got 1.5"},
		{"CREATE SEQUENCE s START WITH 'x'", "Expected an integer argument for START, got 'x'"},
		{"CREATE SEQUENCE s MINVALUE 1e3", "Expected an integer argument for MINVALUE, got 1e3"},
		{"CREATE SEQUENCE s MAXVALUE -2.5", "Expected an integer argument for MAXVALUE, got -2.5"},
		{"CREATE SEQUENCE s INCREMENT BY true", "Expected an integer argument for INCREMENT, got true"},
		{"CREATE SEQUENCE s INCREMENT 1.5 INCREMENT 2", "Expected an integer argument for INCREMENT, got 1.5"},
		{"ALTER SEQUENCE s INCREMENT BY 1.5", "Expected an integer argument for INCREMENT, got 1.5"},
		// TransformAddColumnEntry
		{"ALTER TABLE t ADD COLUMN c INT PRIMARY KEY", "Adding columns with PRIMARY KEY constraints is not supported yet"},
		{"ALTER TABLE t ADD COLUMN c INT CHECK (c > 0)", "Adding columns with CHECK constraints is not supported yet"},
		{"ALTER TABLE t ADD COLUMN c INT REFERENCES o(a)", "Adding columns with FOREIGN KEY constraints is not supported yet"},
		{"ALTER TABLE t ADD COLUMN c INT USING COMPRESSION auto", "Unrecognized option for column compression"},
		{"ALTER TABLE t ADD COLUMN c INT COLLATE nocase", "Only VARCHAR columns can have collations!"},
		{"ALTER TABLE t ADD COLUMN c INT DEFAULT 1 DEFAULT 2", "Cannot define a default value twice"},
		// TransformAlterType + ApplyColumnCollation
		{"ALTER TABLE t ALTER a TYPE INT COLLATE nocase", "Only VARCHAR columns can have collations!"},
		{"ALTER TABLE t ALTER a TYPE COLLATE nocase USING a", "Specify the VARCHAR type to set a collation"},
		// TransformCommentStatement
		{"COMMENT ON COLUMN 'x' IS 'y'", "Invalid column reference: x"},
		{"COMMENT ON COLUMN Abc IS 'y'", "Invalid column reference: Abc"},
		{`COMMENT ON COLUMN "select" IS 'y'`, `Invalid column reference: "select"`},
		// SetCopyOptions / TransformGenericCopyOptionList / BuildGenericCopyOption
		{"COPY t FROM 'f' USING DELIMITERS ',' (DELIMITER ';')", `Unexpected duplicate option "delimiter"`},
		{"COPY t TO 'f' (HEADER, header 1)", `Unexpected duplicate option "header"`},
		{"ATTACH 'x' (TYPE sqlite, type duckdb)", `Unexpected duplicate option "type"`},
		{"CREATE EXTERNAL RESOURCE 'x' AS r (a 1, a 2)", `Unexpected duplicate option "a"`},
		{"COPY t TO 'f' (PARTITION_PATH)", "PARTITION_PATH expects an expression"},
		{"COPY t TO 'f' (PARTITION_PATH (a, b))", "PARTITION_PATH expects a single expression"},
		{"COPY t TO 'f' (PARTITION_PATH (a DESC))", "PARTITION_PATH expects a single expression"},
		// TransformConnectToExternalResource
		{"CONNECT TO NEW TEMPORARY EXTERNAL RESOURCE 'x' (a 1) (b 2)", "CONNECT TO NEW TEMPORARY EXTERNAL RESOURCE: the option list belongs to the resource, so the connection cannot take one of its own. Use `ATTACH TO NEW TEMPORARY EXTERNAL RESOURCE ... AS <name> (options); CONNECT <name>;` instead"},
		// TransformInsertStatement
		{"INSERT INTO t OVERRIDING USER VALUE DEFAULT VALUES", "OVERRIDING SYSTEM|USER VALUE can not be combined with DEFAULT VALUES, please remove one of the two"},
		// TransformCreateExtensionRepositoryStmt
		{"CREATE OR REPLACE EXTENSION REPOSITORY IF NOT EXISTS r PREFIX 'http://x'", "Cannot combine OR REPLACE with IF NOT EXISTS"},
		// TransformDropStatement / TransformDropSecret
		{"DROP SECRET s CASCADE", "CASCADE and RESTRICT are not supported for DROP SECRET"},
		{"DROP TEMPORARY SECRET s FROM x", "Can not combine TEMPORARY with specifying a storage for drop secret"},
		// TransformVacuumParensOptions
		{"VACUUM (ANALYZE, FOO)", `unrecognized VACUUM option "FOO"`},
		// transform_describe.cpp
		{"SUMMARIZE", "Expected table name with SUMMARIZE"},
		{"SHOW ''", "Expected a table name, but got an empty string"},
		{"SHOW TABLES FROM a.b.c", `Expected "SHOW TABLES FROM database", "SHOW TABLES FROM schema", or "SHOW TABLES FROM database.schema"`},
		// TransformMacroDefinition (Identifier formatting is quoted)
		{"CREATE MACRO m(a, A) AS a", `Duplicate parameter "A" in macro definition`},
	}
	for _, tt := range tests {
		if msg := parseErr(t, tt.sql); msg != "Parser Error: "+tt.msg && msg != tt.msg {
			t.Errorf("Parse(%q): message = %q, want %q", tt.sql, msg, tt.msg)
		}
	}
}

func TestStatementAcceptsV2(t *testing.T) {
	// post-parse rejects upstream (NotImplemented/InvalidInput/Binder)
	// and new grammar forms that must transform
	for _, sql := range []string{
		"CREATE TABLE a.b.c.d (i INT)",
		"CREATE TABLE t (a INT CONSTRAINT c NOT NULL CONSTRAINT d UNIQUE)",
		"CREATE TABLE t (a INT REFERENCES o(b) ON DELETE RESTRICT ON UPDATE NO ACTION)",
		"CREATE TABLE t (a INT REFERENCES o)",
		"CREATE INDEX i ON t (a) WHERE a > 1",
		"CREATE SCHEMA a.b.c",
		"CREATE SECURE VIEW v AS SELECT 1",
		"ALTER SEQUENCE s RENAME TO t",
		"ALTER TABLE t ADD COLUMN IF NOT EXISTS c INT NOT NULL",
		"ALTER TABLE t ADD COLUMN s.c INT NOT NULL",
		"ALTER TABLE t DROP CONSTRAINT IF EXISTS c CASCADE",
		"ALTER TABLE t RENAME TO 'x y'",
		"ALTER SCHEMA s RENAME TO t",
		"COPY t TO 'f' (PARTITION_PATH a || 'x')",
		"ATTACH TO EXTERNAL RESOURCE r AS d",
		"CONNECT TO EXTERNAL RESOURCE r (a 1)",
		"DESTROY EXTERNAL RESOURCE r",
		"TRUNCATE t CASCADE",
		"TRUNCATE t AS x RESTRICT",
		"VACUUM (FULL, FOO)",
		"USE 'x.y'",
		"DEALLOCATE 'p'",
		"PREPARE 'p' AS SELECT 1",
		"EXECUTE 'p'",
		"DROP MACRO TABLE a.b.c.d",
		"SHOW a.b",
	} {
		parseOne(t, sql)
	}
}

func TestStatementShapesV2(t *testing.T) {
	// TargetAlias / TruncateOptions
	del := parseAs[*ast.DeleteStatement](t, "DELETE FROM s.t x")
	if ref := del.Table.(*ast.BaseTableRef); ref.Alias != "x" || ref.SchemaName != "s" {
		t.Errorf("delete target = %+v", ref)
	}
	tr := parseAs[*ast.TruncateStatement](t, "TRUNCATE t AS x CASCADE")
	if !tr.Cascade {
		t.Errorf("truncate = %+v", tr)
	}
	// nested schema paths keep the component before the name
	drop := parseAs[*ast.DropStatement](t, "DROP TABLE a.b.c.d, x.y")
	want := []ast.QualifiedName{{Catalog: "a", Schema: "c", Name: "d"}, {Schema: "x", Name: "y"}}
	if !reflect.DeepEqual(drop.Names, want) {
		t.Errorf("drop names = %+v", drop.Names)
	}
	// UpdateSetClauseList concatenates elements and tuples
	upd := parseAs[*ast.UpdateStatement](t, "UPDATE t SET a = 1, (b, c) = (2, 3)")
	if !reflect.DeepEqual(upd.SetInfo.Columns, [][]string{{"a"}, {"b"}, {"c"}}) || len(upd.SetInfo.Expressions) != 3 {
		t.Errorf("update set = %+v", upd.SetInfo)
	}
	ins := parseAs[*ast.InsertStatement](t, "INSERT INTO t OVERRIDING SYSTEM VALUE SELECT 1")
	if ins.Overriding != "SYSTEM" {
		t.Errorf("overriding = %q", ins.Overriding)
	}
	// CREATE INDEX qualifies plain column elements without USING
	idx := createInfo[*ast.CreateIndexInfo](t, "CREATE INDEX i ON t (a, b + 1)")
	if c, ok := idx.Elements[0].Expr.(*ast.ColumnRefExpression); !ok || !reflect.DeepEqual(c.ColumnNames, []string{"t", "a"}) {
		t.Errorf("index element = %+v", idx.Elements[0].Expr)
	}
	view := createInfo[*ast.CreateViewInfo](t, "CREATE SECURE VIEW v WITH (defer_binding = true) AS SELECT 1")
	if !view.Secure || len(view.Options) != 1 {
		t.Errorf("view = %+v", view)
	}
	typ := createInfo[*ast.CreateTypeInfo](t, "CREATE TYPE e AS ENUM ('a', 'b')[]")
	if typ.Type == nil || typ.Type.TypeName != "list" {
		t.Errorf("enum array type = %+v", typ.Type)
	}
	// COPY legacy delimiter, dotted bare file names, stdin
	cp := parseAs[*ast.CopyStatement](t, "COPY t FROM a.b.csv USING DELIMITERS '|'")
	if cp.Info.FilePath != "a.b.csv" || len(cp.Info.Options) != 1 || cp.Info.Options[0].Name != "delimiter" {
		t.Errorf("copy = %+v", cp.Info)
	}
	if cp := parseAs[*ast.CopyStatement](t, "COPY t FROM stdin"); cp.Info.FilePath != "/dev/stdin" {
		t.Errorf("copy stdin = %q", cp.Info.FilePath)
	}
	// LOAD/INSTALL forms and the extension repository statements
	load := parseAs[*ast.LoadStatement](t, "LOAD x FROM core AS y")
	if load.Repository != "core" || !load.RepoIsAlias || load.Alias != "y" {
		t.Errorf("load = %+v", load)
	}
	inst := parseAs[*ast.LoadStatement](t, "FORCE INSTALL AND LOAD x FROM 'http://r' VERSION 'v1'")
	if !inst.LoadAfterInstall || inst.Kind != ast.LoadTypeForceInstall || inst.RepoIsAlias || inst.Version != "v1" {
		t.Errorf("install = %+v", inst)
	}
	repo := parseAs[*ast.LoadStatement](t, "CREATE EXTENSION REPOSITORY IF NOT EXISTS 'r' WITH PREFIX 'http://x' USING PUBLIC KEYS 'a', 'b'")
	if repo.Kind != ast.LoadTypeCreateRepository || repo.Repository != "r" || repo.RepositoryURL != "http://x" ||
		!reflect.DeepEqual(repo.PublicKeys, []string{"a", "b"}) || repo.OnConflict != ast.CreateIgnore {
		t.Errorf("create repository = %+v", repo)
	}
	if d := parseAs[*ast.LoadStatement](t, "DROP EXTENSION REPOSITORY IF EXISTS r"); d.Kind != ast.LoadTypeDropRepository || !d.MissingOK {
		t.Errorf("drop repository = %+v", d)
	}
	att := parseAs[*ast.AttachStatement](t, "ATTACH TO NEW TEMPORARY EXTERNAL RESOURCE 'x' (a) AS d (b 2)")
	if att.Alias != "d" || att.ExternalResource == nil || att.ExternalResource.Provider != "x" ||
		len(att.ExternalResource.Params) != 1 || len(att.Options) != 1 {
		t.Errorf("attach to external resource = %+v", att)
	}
	// SHOW is settings-first; DESCRIBE 'lit' names the table
	show := showRef(t, "SHOW memory_limit")
	if show.ShowType != ast.ShowTypeShow || show.TableName != "memory_limit" || show.Query != nil {
		t.Errorf("show = %+v", show)
	}
	// a string target matches DescribeBaseTableName first (a quoted
	// table name), so it is described through a query
	if d := showRef(t, "DESCRIBE 'f.csv'"); d.ShowType != ast.ShowTypeDescribe || d.Query == nil {
		t.Errorf("describe literal = %+v", d)
	}
	if d := showRef(t, "SHOW 'lit'"); d.ShowType != ast.ShowTypeShow || d.TableName != "lit" {
		t.Errorf("show literal = %+v", d)
	}
	if d := showRef(t, "SHOW databases"); d.ShowType != ast.ShowTypeShowSpecial || d.TableName != `"databases"` {
		t.Errorf("show databases = %+v", d)
	}
	if d := showRef(t, "SHOW s.t"); d.ShowType != ast.ShowTypeShow || d.Query == nil || d.SchemaName != "s" {
		t.Errorf("show qualified = %+v", d)
	}
	if !strings.Contains(parseErr(t, "SUMMARIZE"), "SUMMARIZE") {
		t.Error("bare SUMMARIZE must be rejected")
	}
}

func showRef(t *testing.T, sql string) *ast.ShowRef {
	t.Helper()
	sel := parseAs[*ast.SelectStatement](t, sql)
	node, ok := sel.Node.(*ast.SelectNode)
	if !ok {
		t.Fatalf("%s: node = %T", sql, sel.Node)
	}
	ref, ok := node.FromTable.(*ast.ShowRef)
	if !ok {
		t.Fatalf("%s: from = %T", sql, node.FromTable)
	}
	return ref
}
