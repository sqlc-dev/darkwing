// Command regenerate rebuilds darkwing's conformance corpus from a DuckDB
// source tree and the pinned DuckDB CLI binary: it extracts every SQL
// statement from test/sql/**/*.test and test/fuzzer/**/*.test, asks the
// pinned binary for an accept/reject verdict (Parser Error => reject;
// success or any post-parse error => accept), and writes the meyer-style
// corpus under parser/testdata/corpus/. Expected outputs are never edited
// by hand — rerun this command instead.
//
// Usage:
//
//	regenerate -duckdb-src /path/to/duckdb [-binary /path/to/duckdb-cli]
//	           [-out parser/testdata] [-j 8] [-only substring] [-limit N]
package main

import (
	"flag"
	"fmt"
	"io/fs"
	"log"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"sync"
	"time"

	"github.com/sqlc-dev/darkwing/internal/duckdbsrc"
	"github.com/sqlc-dev/darkwing/internal/sqltest"
	"github.com/sqlc-dev/darkwing/internal/testfile"
)

// maxStatementLen bounds one corpus statement; fuzzer inputs can be huge
// and add nothing past this size.
const maxStatementLen = 32 * 1024

func main() {
	log.SetFlags(0)
	srcDir := flag.String("duckdb-src", "", "path to a DuckDB source tree at the pinned commit (required)")
	binary := flag.String("binary", "", "pinned DuckDB CLI binary (default: $DARKWING_DUCKDB or duckdb on PATH)")
	outDir := flag.String("out", "parser/testdata", "output directory")
	workers := flag.Int("j", runtime.NumCPU()*2, "oracle worker processes")
	timeout := flag.Duration("timeout", 5*time.Second, "per-statement oracle timeout")
	only := flag.String("only", "", "only regenerate source files whose path contains this substring")
	limit := flag.Int("limit", 0, "stop after this many unique statements (0 = no limit)")
	flag.Parse()

	if *srcDir == "" {
		flag.Usage()
		os.Exit(2)
	}
	if err := run(*srcDir, *binary, *outDir, *workers, *timeout, *only, *limit); err != nil {
		log.Fatalf("error: %v", err)
	}
}

type fileStatements struct {
	// rel is the corpus-relative path (e.g. "sql/select/foo.test").
	rel   string
	stmts []string
}

func run(srcDir, binary, outDir string, workers int, timeout time.Duration, only string, limit int) error {
	if binary == "" {
		b, err := duckdbsrc.Find()
		if err != nil {
			return err
		}
		binary = b
	} else if err := duckdbsrc.Verify(binary); err != nil {
		return err
	}

	files, err := collectFiles(srcDir, only)
	if err != nil {
		return err
	}
	log.Printf("extracting from %d .test files", len(files))

	var perFile []fileStatements
	seen := make(map[string]bool)
	extracted, skippedUnstorable, skippedDot, skippedLong, duplicates := 0, 0, 0, 0, 0
	for _, path := range files {
		stmts, err := sqltest.ExtractFile(path)
		if err != nil {
			return fmt.Errorf("extracting %s: %w", path, err)
		}
		rel, err := filepath.Rel(filepath.Join(srcDir, "test"), path)
		if err != nil {
			return err
		}
		var kept []string
		for _, stmt := range stmts {
			extracted++
			sql := stmt.SQL
			switch {
			case len(sql) > maxStatementLen:
				skippedLong++
			case !testfile.CanStore(sql):
				skippedUnstorable++
			case hasDotCommandLine(sql):
				skippedDot++
			case seen[sql]:
				duplicates++
			default:
				seen[sql] = true
				kept = append(kept, sql)
			}
			if limit > 0 && len(seen) >= limit {
				break
			}
		}
		if len(kept) > 0 {
			perFile = append(perFile, fileStatements{rel: filepath.ToSlash(rel), stmts: kept})
		}
		if limit > 0 && len(seen) >= limit {
			break
		}
	}
	log.Printf("extracted %d statements: %d unique kept, %d duplicates, %d unstorable, %d dot-prefixed, %d oversized",
		extracted, len(seen), duplicates, skippedUnstorable, skippedDot, skippedLong)

	verdicts, err := runOracle(binary, timeout, workers, perFile)
	if err != nil {
		return err
	}

	corpusDir := filepath.Join(outDir, "corpus")
	accepted, rejected, unverified := 0, 0, 0
	written := make(map[string]bool)
	filesWritten := 0
	for _, pf := range perFile {
		out := testfile.File{
			Header: []string{
				"source: test/" + pf.rel,
				"pin: " + duckdbsrc.PinnedCommit,
				"oracle: " + duckdbsrc.PinnedVersion,
				"generated by cmd/regenerate - do not edit",
			},
		}
		for _, sql := range pf.stmts {
			v := verdicts[sql]
			if v.TimedOut || v.Crashed {
				// no verdict was actually observed: the CLI died or was
				// cut off, possibly inside its own parser, so recording
				// either accept or reject would be a guess
				unverified++
				continue
			}
			c := testfile.Case{SQL: sql, Reject: v.Reject, Error: v.Error}
			if v.Reject {
				rejected++
			} else {
				accepted++
			}
			out.Cases = append(out.Cases, c)
		}
		if len(out.Cases) == 0 {
			continue
		}
		dest := filepath.Join(corpusDir, filepath.FromSlash(pf.rel))
		if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
			return err
		}
		if err := testfile.Write(dest, &out); err != nil {
			return err
		}
		written[dest] = true
		filesWritten++
	}
	log.Printf("corpus written: %d files, %d must-accept, %d must-reject, %d unverified dropped",
		filesWritten, accepted, rejected, unverified)

	if only != "" || limit > 0 {
		// a partial run regenerates a subset: removing "stale" files or
		// rewriting the corpus-wide README would clobber state belonging
		// to the files that were not regenerated
		log.Printf("partial run (-only/-limit): skipping stale-file cleanup and README update")
		return nil
	}

	if err := removeStale(corpusDir, written); err != nil {
		return err
	}

	readme := fmt.Sprintf(`# darkwing conformance corpus

Generated by cmd/regenerate - do not edit corpus files or expectations by
hand; rerun the tool instead (see PLAN.md, § Conformance oracle and corpus).

- Source: DuckDB test/sql/**/*.test and test/fuzzer/**/*.test
- Pinned commit: %s
- Oracle: DuckDB CLI %s (nightly build of the pinned commit)
- Files: %d, cases: %d (%d must-accept, %d must-reject)
- Statements without an observed verdict (oracle timeout/crash): %d, dropped

Classification: the oracle runs each statement against :memory: with
extension autoloading disabled. An error starting with "Parser Error"
means must-reject (first error line recorded); success or any post-parse
error (Binder, Catalog, ...) means must-accept. Statements for which the
CLI produced no verdict (timeout or crash - possibly inside its own
parser) are excluded rather than guessed. Bind-time nested parses (e.g.
query('...') parsing its string argument) still surface as Parser Errors
and are recorded must-reject; the grammar never sees the inner SQL, so
those cases carry skip entries in the sidecars.

Sidecar files (*.metadata.json) carry todo/skip lists keyed by case
content hash; they are maintained by hand and survive regeneration.
`, duckdbsrc.PinnedCommit, duckdbsrc.PinnedVersion, filesWritten, accepted+rejected, accepted, rejected, unverified)
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(outDir, "README.md"), []byte(readme), 0o644)
}

// removeStale deletes corpus files that this (full) run did not produce -
// leftovers from tests deleted or renamed upstream, whose expectations
// would otherwise keep gating darkwing against an older pin - along with
// their sidecars, and any sidecar orphaned by a vanished corpus file.
func removeStale(corpusDir string, written map[string]bool) error {
	var stale, orphans []string
	err := filepath.WalkDir(corpusDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		switch {
		case strings.HasSuffix(path, ".test"):
			if !written[path] {
				stale = append(stale, path)
			}
		case strings.HasSuffix(path, ".metadata.json"):
			corpus := strings.TrimSuffix(path, ".metadata.json")
			if !written[corpus] {
				orphans = append(orphans, path)
			}
		}
		return nil
	})
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	for _, path := range stale {
		if err := os.Remove(path); err != nil {
			return err
		}
		meta := testfile.MetadataPath(path)
		if err := os.Remove(meta); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	for _, path := range orphans {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	if len(stale) > 0 || len(orphans) > 0 {
		log.Printf("removed %d stale corpus files and %d orphaned sidecars", len(stale), len(orphans))
	}
	return nil
}

func collectFiles(srcDir, only string) ([]string, error) {
	var files []string
	for _, root := range []string{
		filepath.Join(srcDir, "test", "sql"),
		filepath.Join(srcDir, "test", "fuzzer"),
	} {
		err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() || !strings.HasSuffix(path, ".test") {
				return nil
			}
			if only != "" && !strings.Contains(path, only) {
				return nil
			}
			files = append(files, path)
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	sort.Strings(files)
	return files, nil
}

// hasDotCommandLine reports whether any line could be taken for a CLI dot
// command when fed to the oracle (the CLI interprets a leading '.' at a
// statement boundary).
func hasDotCommandLine(sql string) bool {
	for _, line := range strings.Split(sql, "\n") {
		if strings.HasPrefix(line, ".") {
			return true
		}
	}
	return false
}

func runOracle(binary string, timeout time.Duration, workers int, perFile []fileStatements) (map[string]duckdbsrc.Verdict, error) {
	var all []string
	for _, pf := range perFile {
		all = append(all, pf.stmts...)
	}
	log.Printf("running oracle (%s) over %d statements with %d workers", binary, len(all), workers)

	scratch, err := os.MkdirTemp("", "darkwing-oracle-*")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(scratch)

	type result struct {
		sql string
		v   duckdbsrc.Verdict
		err error
	}
	jobs := make(chan string)
	results := make(chan result)
	var wg sync.WaitGroup
	for i := 0; i < workers; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			oracle := &duckdbsrc.Oracle{Binary: binary, Timeout: timeout, Dir: scratch}
			for sql := range jobs {
				v, err := oracle.Run(sql)
				results <- result{sql: sql, v: v, err: err}
			}
		}()
	}
	go func() {
		for _, sql := range all {
			jobs <- sql
		}
		close(jobs)
		wg.Wait()
		close(results)
	}()

	verdicts := make(map[string]duckdbsrc.Verdict, len(all))
	start := time.Now()
	done, timeouts, crashes := 0, 0, 0
	for r := range results {
		if r.err != nil {
			return nil, r.err
		}
		verdicts[r.sql] = r.v
		if r.v.TimedOut {
			timeouts++
		}
		if r.v.Crashed {
			crashes++
		}
		done++
		if done%5000 == 0 {
			elapsed := time.Since(start)
			log.Printf("  %d/%d (%.0f/s, %d timeouts, %d crashes)",
				done, len(all), float64(done)/elapsed.Seconds(), timeouts, crashes)
		}
	}
	log.Printf("oracle done: %d statements in %s (%d timeouts, %d crashes)",
		done, time.Since(start).Round(time.Second), timeouts, crashes)
	return verdicts, nil
}
